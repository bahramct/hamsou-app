// ─────────────────────────────────────────────────────────────────────────────
// load-env — بارگذاری env برای اسکریپت‌های standalone (seed و…)
//
// چرا؟ Next.js خودش `.env.local` را می‌خواند، اما اسکریپت‌هایی که با tsx اجرا می‌شوند
// فقط `.env` را می‌بینند. برای اینکه seed همان کانفیگِ واقعی (مثلاً SMSIR_*) را ببیند،
// اینجا ابتدا `.env.local` و سپس `.env` را لود می‌کنیم. dotenv متغیرهای ازقبل‌تنظیم‌شده
// را override نمی‌کند، پس `.env.local` اولویت دارد.
//
// این فایل باید **اولین import** در seed باشد تا قبل از new PrismaClient اجرا شود.
// ─────────────────────────────────────────────────────────────────────────────

import { config } from "dotenv";

config({ path: ".env.local" });
config(); // .env — بدون override روی مقادیر موجود
